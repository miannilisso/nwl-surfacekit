import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("..", import.meta.url))
const output = `${root}/THIRD_PARTY_NOTICES.md`
const licenses = JSON.parse(
  execFileSync(
    "pnpm",
    ["--filter", "@nwl/surfacekit", "licenses", "list", "--prod", "--json"],
    { cwd: root, encoding: "utf8", maxBuffer: 10 * 1024 * 1024 }
  )
)

const packages = Object.entries(licenses)
  .flatMap(([license, entries]) =>
    entries.map(({ name, versions, homepage }) => ({
      license,
      name,
      versions: [...versions].sort(),
      homepage: homepage ?? "",
    }))
  )
  .sort(
    (left, right) =>
      left.name.localeCompare(right.name) ||
      left.versions.join(",").localeCompare(right.versions.join(","))
  )

const reportTemplate = `# Third-Party Notices

This report is generated from the locked production dependency graph for
@nwl/surfacekit. Regenerate it with pnpm generate:attributions; CI checks it
with pnpm check:attributions.

Generated by pnpm licenses list --filter @nwl/surfacekit --prod --json.

| Package | Version(s) | License | Homepage |
| --- | --- | --- | --- |
${packages
  .map(
    ({ name, versions, license, homepage }) =>
      `| ${name} | ${versions.join(", ")} | ${license} | ${homepage} |`
  )
  .join("\n")}
`
const report = execFileSync(
  "pnpm",
  ["exec", "prettier", "--parser", "markdown"],
  {
    cwd: root,
    encoding: "utf8",
    input: reportTemplate,
  }
)

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== report) {
    console.error(
      "THIRD_PARTY_NOTICES.md is out of date. Run pnpm generate:attributions."
    )
    process.exitCode = 1
  }
} else {
  writeFileSync(output, report)
}
